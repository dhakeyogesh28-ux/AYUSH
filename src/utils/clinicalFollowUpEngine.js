/**
 * Maps chief complaint key / text to relevant pathway
 */
export function getPathwayForComplaint(complaintKey, userText = '') {
  const clean = (userText + ' ' + (complaintKey || '')).toLowerCase();

  if (
    clean.includes('fever') || clean.includes('cough') || clean.includes('cold') ||
    clean.includes('बुखार') || clean.includes('खांसी') || clean.includes('ताप') ||
    clean.includes('खोकला') || clean.includes('காய்ச்சல்') || clean.includes('జ్వరం')
  ) {
    return 'fever_cough';
  }

  if (
    clean.includes('chest') || clean.includes('heart') || clean.includes('छाती') ||
    clean.includes('सीने') || clean.includes('छातीत') || clean.includes('நெஞ்சு') ||
    clean.includes('గుండె') || clean.includes('ಎದೆ')
  ) {
    return 'chest_pain';
  }

  if (
    clean.includes('stomach') || clean.includes('abdomen') || clean.includes('belly') ||
    clean.includes('पेट') || clean.includes('पोट') || clean.includes('வயிறு') ||
    clean.includes('కడుపు') || clean.includes('ಹೊಟ್ಟೆ')
  ) {
    return 'abdominal_pain';
  }

  if (
    clean.includes('headache') || clean.includes('head') || clean.includes('सिर') ||
    clean.includes('डोके') || clean.includes('தலைவலி') || clean.includes('తలనొప్పి') ||
    clean.includes('ತಲೆನೋವು')
  ) {
    return 'headache';
  }

  return 'default_pathway';
}

